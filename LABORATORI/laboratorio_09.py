# Laboratorio 9 - Osservare numeri e caratteri in forme diverse
# Companion digitale - soluzione del laboratorio

numero = 42

print("Binario:", bin(numero))
print("Ottale:", oct(numero))
print("Esadecimale:", hex(numero))
print("Binario 8 bit:", format(numero, "08b"))

carattere = "A"
codice = ord(carattere)

print("Codice di A:", codice)
print("Di nuovo carattere:", chr(codice))
